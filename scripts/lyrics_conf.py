#!/usr/bin/env python3
"""lyrics_conf.py — "ความมั่นใจ" ของเนื้อเพลงที่ใช้อยู่ ให้ทุกฝั่ง import ตัวเดียวกัน

คำถามของผู้ใช้คือ "เพลงไหนเนื้อถูกทั้งหมด และขึ้นตรงช่วงที่ร้อง" ซึ่งเป็น *สองคำถาม*
ที่วัดได้ไม่เท่ากัน:

  "เนื้อถูกไหม"      -> วัดตรง ๆ ไม่ได้ ถ้ามีเนื้อที่ถูกไว้เทียบก็ไม่ต้องหาตั้งแต่แรก
                        anchorPct แยกเนื้อผิดเพลงไม่ได้ (วัดจริงแล้ว: เนื้อเพลงอื่นได้ 56.5%
                        เทียบกับเพลงถูก 66.8%) -> ตัวที่บอกได้จริงคือ "ที่มา"
  "ตรงจังหวะไหม"     -> วัดได้ด้วย onTime แต่ต้องมีไม้บรรทัดที่ *เป็นอิสระ* จากเวลาที่จะวัด

จึงต้องรู้ทั้ง src (ใครพิมพ์ตัวหนังสือ) และ timeSrc (ใครจับเวลา) ก่อนจะสรุปอะไรได้
"""

# เนื้อที่ "คนพิมพ์" — ตัวหนังสือเชื่อได้ เหลือแค่ต้องตรวจเวลา
HAND = frozenset({"manual-lrc", "manual-txt", "manual-edit", "yt-sub",
                  "lrclib", "lrclib-plain", "web/description",
                  "joox", "ytmusic", "netease",      # คลังเนื้อออนไลน์ (งานเลือกเนื้อดีที่สุดใน server)
                  "musixmatch",                      # ต้องมี token บัญชี (ตั้งใน Studio)
                  "library"})                        # เพลงเดียวกันอีกคลิปในคลัง (ใช้เนื้อ+เวลาของคลิปนั้น)
# เกณฑ์คาลิเบรตจาก "ชุดอ้างอิง" = 49 เพลงที่ทั้งเนื้อและเวลามาจากคน (yt-sub/lrclib/manual)
# ซึ่งควรได้คะแนนเต็มถ้าเมตริกสมบูรณ์ แต่วัดจริงได้ p25=24.2 p50=42.3 p75=56.6
# เพราะไม้บรรทัด (ผลถอดเสียง) เองก็ไม่แม่น -> onTime เป็น "ขอบล่าง" ของความถูกต้อง
#   OK_SCORE  55 = ราว p75 ของชุดอ้างอิง -> พูดได้เต็มปากว่าตรวจแล้วตรง
#   BAD_SCORE 20 = ต่ำกว่า p25 ชัดเจน -> แทบไม่มีบรรทัดไหนลงล็อกเลย
#                  วัดจริงมี 10 เพลงในชุดอ้างอิงที่ตกช่องนี้ และตรวจด้วยตาแล้วพังจริง
#                  (ส่วนใหญ่คือ lrclib จับคู่ผิดเวอร์ชัน ได้ 0.0)
# ไม้บรรทัดเปลี่ยนเป็น FA (ตรงภายใน 0.5 วิ ~80% ของบรรทัดที่คนจับเวลา) เกณฑ์จึงขยับขึ้น: 60 = ตรงจริง, <30 = พังชัด
OK_SCORE, BAD_SCORE = 60, 30

LEVELS = ("good", "check", "bad", "auto", "unknown", "none")

# ป้าย "เนื้อแบบไหน" ที่คนสั่งเพลงอ่านรู้เรื่อง — รีโมทกับจอทีวีใช้ข้อความชุดเดียวกัน
SRC_LABEL = {
    "manual-edit":     "แก้เองใน Studio",
    "manual-lrc":      "ไฟล์เนื้อที่วางเอง",
    "manual-txt":      "เนื้อที่วางเอง",
    "yt-sub":          "ซับที่คนทำบน YouTube",
    "lrclib":          "คลังเนื้อ LRCLIB",
    "lrclib-plain":    "คลังเนื้อ LRCLIB",
    "web/description": "คำอธิบายใต้คลิป",
    "yt-auto":         "คำบรรยายอัตโนมัติของ YouTube",
    "joox":            "คลังเนื้อ JOOX",
    "ytmusic":         "YouTube Music",
    "netease":         "คลังเนื้อ NetEase",
    "musixmatch":      "คลังเนื้อ Musixmatch",
    "library":         "เพลงเดียวกันอีกคลิปในคลัง",
    "ocr":             "ตัวหนังสือในคลิป (OCR)",
}


def kind(src: str, time_src: str) -> str:
    """ที่มาของตัวหนังสือ + ใครจับเวลา เช่น "คลังเนื้อ LRCLIB · จับเวลาด้วย AI" """
    if src not in SRC_LABEL:
        return "ถอดเสียงร้องด้วย AI"
    return f"{SRC_LABEL[src]} · {'มีเวลาในตัว' if time_src == 'self' else 'จับเวลาด้วย AI'}"


def time_src_of(j: dict) -> str:
    """timeSrc ของไฟล์ — ไฟล์รุ่นเก่าไม่มีฟิลด์นี้ เดาย้อนหลังจาก src ได้ถูกต้อง"""
    if j.get("timeSrc"):
        return j["timeSrc"]
    return "self" if j.get("src") in ("manual-lrc", "manual-edit", "yt-sub", "lrclib", "yt-auto") else "asr"


def confidence(src: str, time_src: str, on_time: float | None,
               measured_by: str = "", measurable: bool = True) -> tuple[str, str]:
    """คืน (ระดับ, เหตุผลสั้น) — good | check | auto | unknown | none

    กติกา 3 ข้อ ทุกข้อมาจากกับดักที่โค้ดนี้เคยตกมาแล้วจริง ๆ:
      1. "ไม่เคยวัด" ไม่ใช่ "ดี" ต้องขึ้นว่ายังไม่ได้ตรวจ
      2. ไม้บรรทัดที่มาจากแหล่งเดียวกับเวลา = วัดตัวเอง ห้ามนับ
         (เคยเจอตอน A/B โมเดลถอดเสียง: เทียบกับแคชของตัวเองชนะทุกครั้ง)
      3. เนื้อจากเครื่องถอดเสียง ต่อให้เวลาตรง 100% ก็ยังการันตีตัวหนังสือไม่ได้
    """
    if src not in HAND:                              # yt-auto
        return "auto", "เนื้อมาจากเครื่องถอดเสียงของ YouTube"
    if measured_by and measured_by == (time_src or "self"):
        on_time = None                               # กติกา 2: วัดตัวเอง = ไม่ได้วัด
    if on_time is None:
        return ("unknown", "ยังไม่ได้ตรวจเวลา") if measurable \
               else ("none", "ไม่มีไม้บรรทัดอิสระให้ตรวจ")
    if on_time >= OK_SCORE:
        return "good", f"ตรวจแล้ว เวลาตรง {on_time:.0f}%"
    if on_time >= BAD_SCORE:
        return "check", f"เวลาตรง {on_time:.0f}% (ไม้บรรทัดเองก็ไม่แม่น ระดับนี้ถือว่าปกติ)"
    return "bad", f"แทบไม่มีบรรทัดไหนตรงเลย ({on_time:.0f}%) น่าจะผิดเพลงหรือเวลาเลื่อนทั้งเพลง"
